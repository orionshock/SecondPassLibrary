def _path_matches(path: str, candidate: str) -> bool:
    return path.startswith(candidate) if candidate.endswith("/") else path == candidate


def markers_for_test(*, path: str, nodeid: str) -> Iterable[str]:
    """Return the audited lane markers for one collected test."""

    for marker_name, candidates in _PATH_MARKERS.items():
        if any(_path_matches(path, candidate) for candidate in candidates):
            yield marker_name
    for marker_name, prefixes in _NODE_MARKERS.items():
        if any(nodeid.startswith(prefix) for prefix in prefixes):
            yield marker_name
